import logging
import re
import uuid
from datetime import date
from pathlib import Path
from typing import List

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor

from app.config import OUTPUT_DIR
from app.executor import SectionResult
from app.schemas import Plan

logger = logging.getLogger("agent.document")

NAVY = RGBColor(0x1F, 0x3A, 0x5F)
GREY = RGBColor(0x59, 0x59, 0x59)
FONT = "Calibri"


class DocumentError(Exception):
    """Raised when the Word document cannot be built or saved."""


def _set_style_font(style, size, bold=False, color=None):
    style.font.name = FONT
    style.font.size = Pt(size)
    style.font.bold = bold
    if color is not None:
        style.font.color.rgb = color
    # Remove theme font overrides so our font is actually used.
    rfonts = style.element.rPr.rFonts
    for attr in ("w:asciiTheme", "w:hAnsiTheme", "w:eastAsiaTheme", "w:cstheme"):
        rfonts.attrib.pop(qn(attr), None)
    rfonts.set(qn("w:eastAsia"), FONT)


def _setup_styles(doc: Document):
    _set_style_font(doc.styles["Normal"], 11)
    normal = doc.styles["Normal"].paragraph_format
    normal.space_after = Pt(8)
    normal.line_spacing = 1.15

    _set_style_font(doc.styles["Heading 1"], 16, bold=True, color=NAVY)
    heading = doc.styles["Heading 1"].paragraph_format
    heading.space_before = Pt(18)
    heading.space_after = Pt(8)
    heading.keep_with_next = True

    _set_style_font(doc.styles["List Bullet"], 11)
    doc.styles["List Bullet"].paragraph_format.space_after = Pt(4)


def _add_field(run, instruction: str):
    """Insert a Word field (e.g. PAGE) into a run."""
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = instruction
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    run._r.append(begin)
    run._r.append(instr)
    run._r.append(end)


def _setup_page(doc: Document, title: str):
    section = doc.sections[0]
    section.left_margin = section.right_margin = Inches(1)
    section.top_margin = section.bottom_margin = Inches(1)
    section.different_first_page_header_footer = True  # clean title page

    header_p = section.header.paragraphs[0]
    header_p.text = title
    header_p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    for run in header_p.runs:
        run.font.size = Pt(9)
        run.font.color.rgb = GREY

    footer_p = section.footer.paragraphs[0]
    footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    label = footer_p.add_run("Page ")
    label.font.size = Pt(9)
    label.font.color.rgb = GREY
    number = footer_p.add_run()
    number.font.size = Pt(9)
    number.font.color.rgb = GREY
    _add_field(number, "PAGE")


def _add_title_page(doc: Document, plan: Plan):
    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_p.paragraph_format.space_before = Pt(150)
    run = title_p.add_run(plan.title)
    run.font.size = Pt(28)
    run.font.bold = True
    run.font.color.rgb = NAVY

    type_p = doc.add_paragraph()
    type_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = type_p.add_run(plan.document_type.title())
    run.font.size = Pt(16)
    run.font.color.rgb = GREY

    date_p = doc.add_paragraph()
    date_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    date_p.paragraph_format.space_before = Pt(60)
    run = date_p.add_run(f"Prepared on {date.today().strftime('%d %B %Y')}")
    run.font.size = Pt(11)
    run.font.color.rgb = GREY

    by_p = doc.add_paragraph()
    by_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = by_p.add_run("Generated by the Autonomous Document Agent")
    run.font.size = Pt(11)
    run.font.color.rgb = GREY

    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def _add_assumptions(doc: Document, plan: Plan):
    if not plan.assumptions:
        return
    doc.add_heading("Assumptions and Scope Notes", level=1)
    intro = doc.add_paragraph(
        "The request left some details open. The following assumptions were made "
        "while preparing this document:"
    )
    intro.runs[0].italic = True
    for assumption in plan.assumptions:
        doc.add_paragraph(assumption, style="List Bullet")


def _add_sections(doc: Document, sections: List[SectionResult]):
    for number, section in enumerate(sections, start=1):
        doc.add_heading(f"{number}. {section.heading}", level=1)
        for kind, text in section.blocks:
            if kind == "bullet":
                doc.add_paragraph(text, style="List Bullet")
            else:
                doc.add_paragraph(text)


def _add_failed_note(doc: Document, plan: Plan):
    failed = [t.title for t in plan.tasks if t.status == "failed"]
    if not failed:
        return
    doc.add_heading("Document Notes", level=1)
    note = doc.add_paragraph(
        "The following sections could not be generated and should be completed manually: "
        + "; ".join(failed)
        + "."
    )
    note.runs[0].italic = True


def _slugify(text: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "_", text).strip("_")
    return slug[:50] or "document"


def build_document(plan: Plan, sections: List[SectionResult]) -> str:
    """Build the .docx, save it in OUTPUT_DIR, and return the filename."""
    try:
        doc = Document()
        _setup_styles(doc)
        _setup_page(doc, plan.title)
        _add_title_page(doc, plan)
        _add_assumptions(doc, plan)
        _add_sections(doc, sections)
        _add_failed_note(doc, plan)

        output_dir = Path(OUTPUT_DIR)
        output_dir.mkdir(parents=True, exist_ok=True)
        filename = f"{_slugify(plan.title)}_{uuid.uuid4().hex[:6]}.docx"
        doc.save(output_dir / filename)
    except Exception as exc:
        raise DocumentError(f"Could not build the Word document: {exc}") from exc

    logger.info("Saved document: %s", filename)
    return filename